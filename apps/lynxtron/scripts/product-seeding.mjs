// What a fixture seeder needs to make its state through the product: the
// scripted provider as the only provider of a state directory, and the built
// app, hidden, on that directory, taking the commands the UI sends. Nothing
// here writes the server's database.

import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";
import * as NodeProcess from "node:process";
import * as NodeURL from "node:url";

import { openOwnedDevToolSession, readOwnedListeningTcpPorts } from "./devtool-client-identity.mjs";
import { SCRIPTED_MODEL_ID } from "./fixtures/scripted-provider.mjs";

const appRoot = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "..");
const devToolCli = NodePath.resolve(
  NodeProcess.env.LYNX_DEVTOOL_CLI ??
    NodePath.join(NodeOS.homedir(), ".agents/skills/lynx-devtool/scripts/index.mjs"),
);

export const SCRIPTED_MODEL_SELECTION = { instanceId: "grok", model: SCRIPTED_MODEL_ID };

/**
 * Makes the scripted provider the one provider of the state in `baseDir`: the
 * Grok driver runs a launcher for it, every real provider is switched off, and
 * the app's saved model is the scripted one. `chunkDelayMs` is the pause
 * between the words of a reply; a fixture that only needs the finished turn
 * passes 0.
 */
export function configureScriptedProvider(baseDir, { chunkDelayMs } = {}) {
  const launcher = NodePath.join(baseDir, "scripted-provider");
  NodeFS.writeFileSync(
    launcher,
    `#!/bin/sh\n${
      chunkDelayMs === undefined
        ? ""
        : `export T3_SCRIPTED_PROVIDER_CHUNK_DELAY_MS=${chunkDelayMs}\n`
    }exec ${JSON.stringify(NodeProcess.execPath)} ${JSON.stringify(
      NodePath.join(appRoot, "scripts/fixtures/scripted-provider.mjs"),
    )} "$@"\n`,
    { mode: 0o755 },
  );
  NodeFS.writeFileSync(
    NodePath.join(baseDir, "userdata", "settings.json"),
    `${JSON.stringify(
      {
        // Codex and Claude run unconfigured, so they are switched off by name.
        // The gates enable OpenCode in a state that does not decide it. Every
        // other built-in driver stays off without an entry.
        providerInstances: {
          codex: { driver: "codex", enabled: false },
          claudeAgent: { driver: "claudeAgent", enabled: false },
          opencode: { driver: "opencode", enabled: false },
          grok: { driver: "grok", enabled: true, config: { binaryPath: launcher } },
        },
        // Thread titles are generated by a provider too; keep that on the script.
        textGenerationModelSelection: SCRIPTED_MODEL_SELECTION,
      },
      null,
      2,
    )}\n`,
  );
  NodeFS.writeFileSync(
    NodePath.join(baseDir, "lynxtron-prefs.json"),
    `${JSON.stringify(
      { themePreference: "dark", clientSettings: {}, modelSelection: SCRIPTED_MODEL_SELECTION },
      null,
      2,
    )}\n`,
  );
}

function devInstance(args) {
  return NodeChildProcess.execFileSync(
    NodeProcess.execPath,
    [NodePath.join(appRoot, "scripts/dev-instance.mjs"), ...args],
    { cwd: appRoot, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
  );
}

async function waitUntil(read, timeoutMs, label) {
  const deadline = Date.now() + timeoutMs;
  let latest;
  while (Date.now() < deadline) {
    latest = await read();
    if (latest) return latest;
    await new Promise((resolve) => setTimeout(resolve, 25));
  }
  throw new Error(`Timed out waiting for ${label}.`);
}

// The part of the client state a seeder waits on and records. Message texts
// stay in the app; a long thread's would not fit one reply.
const STATE_EXPRESSION = `(() => {
  const state = globalThis.__T3_LYNXTRON_CLIENT_STATE__?.();
  if (!state) return "null";
  return JSON.stringify({
    ready: globalThis.__T3_LYNXTRON_READINESS__?.().ready === true,
    projects: state.projects,
    threadIds: state.threadIds,
    activeThreadId: state.activeThreadId ?? null,
    activeThread: state.activeThread ?? null,
    sessionStatus: state.sessionStatus,
    sessionError: state.sessionError ?? null,
    activeTurnId: state.activeTurnId,
    latestTurn: state.latestTurn,
    selectedProvider: state.selectedProvider ?? null,
    messages: state.messages.map((message) => ({
      id: message.id,
      role: message.role,
      turnId: message.turnId ?? null,
      streaming: message.streaming === true,
    })),
    checkpoints: state.checkpoints,
  });
})()`;

/**
 * Runs `seed` against the built app, hidden, on the state in `baseDir`, and
 * stops the app whatever happens. `seed` gets:
 *
 * - `state()`: the client state the UI renders from, as far as seeders need;
 * - `waitForState(predicate, label)`: that state once `predicate` holds;
 * - `command(name, input)`: a command, sent as the UI sends it;
 * - `createThread(title)`: a thread on the one project, shown in the app;
 * - `runTurn(threadId, text)`: a prompt, and the state once its turn is done.
 *
 * The preferences file the app saves is put back as it was. One DevTool
 * session stays open for the whole run: a session opened later than about
 * twenty seconds after launch gets no answer from the background thread.
 */
export async function seedThroughApp(baseDir, seed, { timeoutMs = 60_000 } = {}) {
  const prefsPath = NodePath.join(baseDir, "lynxtron-prefs.json");
  const prefsBefore = NodeFS.existsSync(prefsPath) ? NodeFS.readFileSync(prefsPath) : null;
  const manifest = JSON.parse(
    NodeFS.readFileSync(NodePath.join(baseDir, "visual-state.json"), "utf8"),
  );
  const started = JSON.parse(
    devInstance([
      "start",
      baseDir,
      "--env",
      `T3_LYNXTRON_PROJECT_CWD=${manifest.project.workspaceRoot}`,
    ]),
  );
  let session;
  let seeded = false;
  try {
    session = await waitUntil(
      async () => {
        // The port opens a moment after launch.
        try {
          return await openOwnedDevToolSession({
            appName: "@t3tools/lynxtron",
            devToolCli,
            ownedPorts: readOwnedListeningTcpPorts(started.pid),
          });
        } catch {
          return null;
        }
      },
      20_000,
      "the app's DevTool session",
    );
    const evaluate = async (expression) => {
      const response = await session.runCdp("Runtime.evaluate", {
        expression,
        returnByValue: true,
        awaitPromise: true,
      });
      const result = response?.result?.result ?? response?.result ?? response;
      if (typeof result?.value !== "string") {
        throw new Error(`The app did not answer: ${JSON.stringify(response).slice(0, 400)}`);
      }
      return JSON.parse(result.value);
    };
    // Evaluate can fail while the app is still starting.
    const state = () => evaluate(STATE_EXPRESSION).catch(() => null);
    const waitForState = async (predicate, label) => {
      let latest = null;
      try {
        return await waitUntil(
          async () => {
            latest = await state();
            return latest !== null && predicate(latest) ? latest : null;
          },
          timeoutMs,
          label,
        );
      } catch (error) {
        throw new Error(`${error.message} Last state: ${JSON.stringify(latest).slice(0, 1500)}`);
      }
    };
    const command = async (name, input) => {
      const outcome = await evaluate(
        `globalThis.__T3_LYNXTRON_COMMAND__(${JSON.stringify(name)}, ${JSON.stringify(input)})
          .then((value) => JSON.stringify({ value: value ?? null }))
          .catch((error) => JSON.stringify({ error: error?.message ?? String(error) }))`,
      );
      if (outcome.error !== undefined) throw new Error(`${name} failed: ${outcome.error}`);
      return outcome.value;
    };
    const ready = await waitForState(
      (current) =>
        current.ready &&
        current.projects.length === 1 &&
        current.selectedProvider?.instanceId === SCRIPTED_MODEL_SELECTION.instanceId &&
        current.selectedProvider.status === "ready",
      "the app to be ready on the scripted provider",
    );
    // The state a thread's last turn ended in, which is where its next begins.
    let settled = null;
    const result = await seed({
      state,
      waitForState,
      command,
      async createThread(title) {
        const { threadId } = await command("createThread", {
          projectId: ready.projects[0].id,
          title,
        });
        await waitForState((current) => current.threadIds.includes(threadId), "the new thread");
        await evaluate(
          `(globalThis.__T3_LYNXTRON_SELECT_THREAD__(${JSON.stringify(threadId)}), "null")`,
        );
        await waitForState(
          (current) => current.activeThreadId === threadId,
          "the new thread to be shown",
        );
        return threadId;
      },
      async runTurn(threadId, text) {
        const before =
          settled?.activeThreadId === threadId
            ? settled
            : await waitForState(
                (current) => current.activeThreadId === threadId,
                "the thread to be shown",
              );
        await command("sendPrompt", { threadId, text, planModeEnabled: false });
        settled = await waitForState(
          (current) =>
            current.activeThreadId === threadId &&
            current.latestTurn !== null &&
            current.latestTurn.turnId !== before.latestTurn?.turnId &&
            current.latestTurn.state !== "running" &&
            current.activeTurnId === null &&
            current.messages.length >= before.messages.length + 2 &&
            current.messages.every((message) => !message.streaming),
          `the turn for ${JSON.stringify(text.slice(0, 60))}`,
        );
        return settled;
      },
    });
    seeded = true;
    return result;
  } finally {
    await session?.close();
    const stopped = JSON.parse(devInstance(["stop", baseDir]));
    // The app's log explains a failed seeding; a seeded fixture does not keep it.
    if (seeded) NodeFS.rmSync(NodePath.join(baseDir, "dev-instance.log"), { force: true });
    if (prefsBefore === null) NodeFS.rmSync(prefsPath, { force: true });
    else NodeFS.writeFileSync(prefsPath, prefsBefore);
    if (!stopped.exited || !stopped.childrenExited) {
      throw new Error(`The app or its server did not exit: ${JSON.stringify(stopped)}`);
    }
  }
}
